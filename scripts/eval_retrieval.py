"""Offline retrieval-quality evaluation for the RAG store. Zero cost: no Gemini calls.

For each case, the RELEVANT pages are defined objectively as every page of the
source PDF that contains an anchor phrase (e.g. "attrition"). The query itself
is worded differently, so this measures whether semantic search finds the
right pages, not keyword matching. Reports Hit@2 (what rag_worker actually
retrieves per query), Hit@4, and MRR@4.

    python scripts/eval_retrieval.py [--persist-dir ./data/chroma_db]
"""
import argparse
import sys
from pathlib import Path

import pymupdf

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from backend.app.rag.vector_store import FinancialVectorStore  # noqa: E402

REPORTS = {
    "TCS.NS": "data/annual_reports/TCS_annual-report-2025-2026.pdf",
    "INFY.NS": "data/annual_reports/infosys.pdf",
    "RELIANCE.NS": "data/annual_reports/reliance.pdf",
}

# (ticker, query as a user/planner would phrase it, anchor phrases defining relevance)
CASES = [
    ("TCS.NS", "How is employee turnover trending?", ("attrition",)),
    ("TCS.NS", "Cash generated by the business after capital spending", ("free cash flow",)),
    ("TCS.NS", "Total contract value of new deals signed", ("tcv", "total contract value")),
    ("TCS.NS", "Did the company repurchase its own shares?", ("buyback", "buy-back", "bought back")),
    ("TCS.NS", "Profitability of operations and margin trend", ("operating margin",)),
    ("INFY.NS", "Big multi-year client contracts won this year", ("large deal",)),
    ("INFY.NS", "How many employees left the company voluntarily?", ("attrition",)),
    ("INFY.NS", "Margin performance versus guidance", ("operating margin",)),
    ("INFY.NS", "Cash generated by the business after capital spending", ("free cash flow",)),
    ("INFY.NS", "Total contract value of new deals signed", ("tcv", "total contract value")),
    ("RELIANCE.NS", "Performance of the oil to chemicals refining business", ("O2C",)),
    ("RELIANCE.NS", "New energy giga-factories and clean power plans", ("green energy",)),
    ("RELIANCE.NS", "Telecom and digital platform business performance", ("digital services",)),
    ("RELIANCE.NS", "Did the company repurchase its own shares?", ("buyback", "buy-back", "bought back")),
    ("RELIANCE.NS", "How is employee turnover trending?", ("attrition",)),
]


def relevant_pages(pdf_path: str, anchors: tuple[str, ...]) -> set[int]:
    doc = pymupdf.open(pdf_path)
    texts = [page.get_text("text").lower() for page in doc]
    return {i + 1 for i, text in enumerate(texts) if any(a.lower() in text for a in anchors)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--persist-dir", default=None, help="ChromaDB directory (defaults to settings)")
    args = parser.parse_args()
    store = FinancialVectorStore(args.persist_dir) if args.persist_dir else FinancialVectorStore()

    hit2 = hit4 = rr_total = 0.0
    print(f"{'ticker':<12} {'anchor':<17} {'#rel':>4}  {'retrieved pages (top 4)':<24} rank")
    for ticker, query, anchors in CASES:
        relevant = relevant_pages(REPORTS[ticker], anchors)
        pages = [hit["page"] for hit in store.query(query, ticker, top_k=4)]
        rank = next((i + 1 for i, p in enumerate(pages) if p in relevant), None)
        hit2 += rank is not None and rank <= 2
        hit4 += rank is not None
        rr_total += 1 / rank if rank else 0
        print(f"{ticker:<12} {anchors[0]:<17} {len(relevant):>4}  {str(pages):<24} {rank or '-'}")

    n = len(CASES)
    print(f"\nHit@2 {hit2 / n:.0%}   Hit@4 {hit4 / n:.0%}   MRR@4 {rr_total / n:.2f}   ({n} queries)")


if __name__ == "__main__":
    main()
